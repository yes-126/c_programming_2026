#include <stdio.h>

int main() {
    for (int i = 0; i < 10; i++) {
        for (int j = 0; j < 5; j++) {
            if (j == i) {
                break;
            }
            printf("i: %d, j: %d\n", i, j);
        }
    }
    return 0;
}

// for가 중첩된 경우, break가 있으면 현재 실행 중인 for만 break됨
/*제미나이!
바깥쪽 루프 (i 가 0부터 9까지): 총 10번 반복하려고 시도
안쪽 루프 (j 가 0부터 4까지): 바깥쪽 루프가 한 번 돌 때마다 최대 5번씩 반복하려고 함
탈출 조건 (if (j == i)): 만약 j와 i의 값이 같아지면, break, 안쪽 루프(j)만 종료시키고
바깥쪽 루프(i)는 다음 숫자로 계속 진행함
ex. i = 2일 때
j는 0, 1일 때까지 출력되고 2일 때 if문의 조건문이 참이 되면서 break가 실행됨.*/

